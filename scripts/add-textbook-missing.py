GRADE_TO_AGE = {
    1: "초등 1학년", 2: "초등 저학년", 3: "초등 저학년",
    4: "초등 고학년", 5: "초등 고학년", 6: "초등 고학년",
}
GRADE_TO_GENRE = {
    1: "그림책", 2: "그림책", 3: "동화",
    4: "동화", 5: "소설", 6: "소설",
}


def main():
    d = json.load(open(PATH, encoding="utf-8"))

    if not any(s["id"] == "textbook" for s in d["meta"]["sources"]):
        d["meta"]["sources"].append({
            "id": "textbook",
            "name": "교과서 수록도서",
            "fullName": "초등학교 국어 교과서 수록도서",
            "url": "",
            "description": "초등학교 국어 교과서(2022·2015 개정 교육과정)에 수록된 문학 작품의 원작 단행본",
            "badge": {"text": "교과서", "color": "#27ae60"}
        })

    added = merged = already = 0

    for isbn, title, author, grade, unit, why in BOOKS:
        age = GRADE_TO_AGE[grade]
        genre = GRADE_TO_GENRE[grade]

        if isbn in d["books"]:
            existing = d["books"][isbn]
            lists = set(existing.get("lists", []))
            changed = False
            if "textbook" not in lists:
                lists.add("textbook"); existing["lists"] = sorted(lists); changed = True
            if not existing.get("textbookGrade"):
                existing["textbookGrade"] = grade; changed = True
            if unit and not existing.get("textbookUnit"):
                existing["textbookUnit"] = unit; changed = True
            if not existing.get("why") and why:
                existing["why"] = why; changed = True
            if changed:
                print(f"병합 -> {isbn} {title}")
                merged += 1
            else:
                print(f"이미 있음 -> {title}")
                already += 1
        else:
            entry = {
                "isbn": isbn,
                "title": title,
                "author": author,
                "publisher": "",
                "lists": ["textbook"],
                "year": 2015 if grade >= 5 else 2022,
                "targetAge": age,
                "genre": genre,
                "why": why,
                "textbookGrade": grade,
                "textbookUnit": unit,
            }
            d["books"][isbn] = entry
            print(f"신규 -> {isbn} {title}")
            added += 1

    json.dump(d, open(PATH, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    tb_total = len([b for b in d["books"].values() if isinstance(b, dict) and b.get("textbookGrade")])
    print(f"\n완료: 신규 {added} | 병합 {merged} | 이미있음 {already}")
    print(f"교과서 수록 DB 총계: {tb_total}권")


if __name__ == "__main__":
    main()
