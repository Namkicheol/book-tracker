def fetch_isbn(title, author_hint):
    q = urllib.parse.quote(title)
    url = f"{WORKER}/aladin/search?Query={q}&QueryType=Title&SearchTarget=Book&MaxResults=5"
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "moms-books/1.0"})
        with urllib.request.urlopen(req, timeout=12) as r:
            data = json.loads(r.read())
        items = data.get("item", []) if isinstance(data, dict) else (data if isinstance(data, list) else [])
        for item in items:
            t = item.get("title", "")
            a = item.get("author", "") or ""
            title_match = title[:4] in t or t[:4] in title
            author_match = not author_hint or any(w in a for w in author_hint.split())
            if title_match and author_match:
                return item.get("isbn13") or item.get("isbn") or ""
        return items[0].get("isbn13", "") if items else ""
    except Exception as e:
        print(f"  lookup 실패: {e}")
        return ""


def main():
    d = json.load(open(PATH, encoding="utf-8"))

    if not any(s["id"] == "textbook" for s in d["meta"]["sources"]):
        d["meta"]["sources"].append({
            "id": "textbook",
            "name": "교과서 수록도서",
            "fullName": "초등학교 국어 교과서 수록도서",
            "url": "",
            "description": "초등학교 국어 교과서(2022·2015 개정 교육과정)에 수록된 문학 작품의 원작 단행본",
            "badge": {"text": "교과서", "color": "#27ae60"}
        })

    # 제목 → isbn 역매핑 (중복 방지)
    title_to_isbn = {v["title"]: k for k, v in d["books"].items() if isinstance(v, dict)}

    added = merged = skipped = already = 0

    for title, author, grade, unit, why in BOOKS:
        age = GRADE_TO_AGE[grade]
        genre = GRADE_TO_GENRE[grade]
        print(f"처리: {title} [{grade}학년 {unit}]...", end=" ", flush=True)

        # 이미 동일 제목이 있으면 merge
        if title in title_to_isbn:
            isbn = title_to_isbn[title]
            existing = d["books"][isbn]
            changed = False
            lists = set(existing.get("lists", []))
            if "textbook" not in lists:
                lists.add("textbook"); existing["lists"] = sorted(lists); changed = True
            if not existing.get("textbookGrade"):
                existing["textbookGrade"] = grade; changed = True
            if unit and not existing.get("textbookUnit"):
                existing["textbookUnit"] = unit; changed = True
            if changed:
                print(f"병합 -> {isbn}")
                merged += 1
            else:
                print("이미 있음")
                already += 1
            time.sleep(0.1)
            continue

        isbn = fetch_isbn(title, author)
        if not isbn:
            print("ISBN 없음 - 건너뜀")
            skipped += 1
            time.sleep(0.3)
            continue

        isbn = str(isbn).replace("-", "")

        if isbn in d["books"]:
            existing = d["books"][isbn]
            lists = set(existing.get("lists", []))
            changed = False
            if "textbook" not in lists:
                lists.add("textbook"); existing["lists"] = sorted(lists); changed = True
            if not existing.get("textbookGrade"):
                existing["textbookGrade"] = grade; changed = True
            if unit and not existing.get("textbookUnit"):
                existing["textbookUnit"] = unit; changed = True
            if not existing.get("why") and why:
                existing["why"] = why; changed = True
            if changed:
                print(f"병합(ISBN) -> {isbn}")
                merged += 1
            else:
                print("이미 있음")
                already += 1
        else:
            entry = {
                "isbn": isbn,
                "title": title,
                "author": author,
                "publisher": "",
                "lists": ["textbook"],
                "year": 2022,
                "targetAge": age,
                "genre": genre,
                "why": why,
                "textbookGrade": grade,
                "textbookUnit": unit,
            }
            d["books"][isbn] = entry
            title_to_isbn[title] = isbn
            print(f"신규 -> {isbn}")
            added += 1

        time.sleep(0.35)

    json.dump(d, open(PATH, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    tb_total = len([b for b in d["books"].values() if isinstance(b, dict) and b.get("textbookGrade")])
    print(f"\n완료: 신규 {added} | 병합 {merged} | 이미있음 {already} | 건너뜀 {skipped}")
    print(f"교과서 수록 DB 총계: {tb_total}권")


if __name__ == "__main__":
    main()
