def main():
    db = json.load(open(DATA, encoding='utf-8'))
    books = db['books']
    enriched = json.load(open('/tmp/wb_enriched.json', encoding='utf-8'))

    added = 0
    skipped = []
    missing_why = []
    for isbn, v in enriched.items():
        if isbn in DROP:
            skipped.append((isbn, 'duplicate edition'))
            continue
        if isbn in books:
            skipped.append((isbn, 'already exists'))
            continue
        why = WHY.get(isbn, '')
        if not why:
            missing_why.append((isbn, v['title']))
            continue
        obj = {
            'isbn': isbn,
            'title': v['title'],
            'author': v['author'],
            'publisher': v['publisher'],
            'year': v['year'],
            'ar': v['ar'],
            'language': 'en',
            'lexile': v['lexile'],
            'thumbnail': v['thumbnail'],
            'genre': '원서',
            'lists': [],
            'why': why,
        }
        books[isbn] = obj
        added += 1

    if missing_why:
        print('ABORT: missing why for', missing_why)
        return

    # Append-only: preserve existing insertion order (file is NOT ISBN-sorted;
    # sorting would churn the entire 5600+ entry diff). New keys are added at
    # the end by dict insertion above, so no reordering needed.
    db['meta']['lastUpdated'] = '2026-05-30'

    with open(DATA, 'w', encoding='utf-8') as f:
        json.dump(db, f, ensure_ascii=False, indent=2)
        f.write('\n')

    print(f'added {added}, skipped {len(skipped)}: {skipped}')
    print(f'total books now {len(db["books"])}')


if __name__ == '__main__':
    main()
