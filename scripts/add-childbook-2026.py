def fetch(url):
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "moms-books/1.0"})
        with urllib.request.urlopen(req, timeout=12) as r:
            return json.loads(r.read())
    except Exception as e:
        print(f"    [ERR] {e}")
        return None

def search(title):
    q = urllib.parse.quote(title[:20])
    url = f"{WORKER}/aladin/search?Query={q}&QueryType=Title&SearchTarget=Book&MaxResults=5"
    data = fetch(url)
    if not data:
        return None
    items = data.get("item", [])
    key = title[:4]
    for item in items:
        if key in item.get("title", ""):
            return item
    return items[0] if items else None

def main():
    with open(REC_PATH, encoding="utf-8") as f:
        rec = json.load(f)
    rec_books = rec["books"]

    added = tagged = failed = 0
    total = len(BOOKS)
    print(f"2026 어린이도서연구회 {total}권 처리 중...\n")

    for i, (title, author_hint, age) in enumerate(BOOKS):
        item = search(title)
        if not item:
            print(f"  [{i+1:3d}/{total}] 실패: {title}")
            failed += 1
            time.sleep(0.5)
            continue

        isbn = str(item.get("isbn13", "")).replace("-", "")
        if not isbn:
            print(f"  [{i+1:3d}/{total}] ISBN없음: {title}")
            failed += 1
            time.sleep(0.5)
            continue

        if isbn in rec_books:
            b = rec_books[isbn]
            if "childbook" not in b.get("lists", []):
                b.setdefault("lists", []).append("childbook")
                tagged += 1
                print(f"  [{i+1:3d}/{total}] 태그추가: {b['title'][:30]}")
            else:
                print(f"  [{i+1:3d}/{total}] 이미완료: {b['title'][:30]}")
        else:
            genre = "그림책" if age == "유아" else "문학"
            rec_books[isbn] = {
                "isbn": isbn,
                "title": item.get("title", title),
                "author": item.get("author", author_hint),
                "publisher": item.get("publisher", ""),
                "thumbnail": item.get("cover", ""),
                "year": int(item.get("pubDate", "2025")[:4]) if item.get("pubDate") else 2025,
                "targetAge": age,
                "genre": genre,
                "lists": ["childbook"],
                "why": "어린이도서연구회 2026 권장도서로 선정된 책입니다.",
            }
            added += 1
            print(f"  [{i+1:3d}/{total}] 추가({age}): {item.get('title','')[:30]}")
        time.sleep(0.35)

    with open(REC_PATH, "w", encoding="utf-8") as f:
        json.dump(rec, f, ensure_ascii=False, indent=2)

    print(f"\n완료 — 신규: {added}, 태그추가: {tagged}, 실패: {failed}, 총: {len(rec_books)}권")

if __name__ == "__main__":
    main()
