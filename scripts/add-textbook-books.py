def fetch_isbn(title, author_hint):
    q = urllib.parse.quote(title)
    url = f"{WORKER}/aladin/search?Query={q}&QueryType=Title&SearchTarget=Book&MaxResults=5"
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "moms-books/1.0"})
        with urllib.request.urlopen(req, timeout=12) as r:
            data = json.loads(r.read())
        items = data.get("item", []) if isinstance(data, dict) else (data if isinstance(data, list) else [])
        for item in items:
            t = item.get("title", "")
            a = item.get("author", "") or ""
            title_match = title[:4] in t or t[:4] in title
            author_match = not author_hint or any(w in a for w in author_hint.split())
            if title_match and author_match:
                return item.get("isbn13") or item.get("isbn") or ""
        return items[0].get("isbn13", "") if items else ""
    except Exception as e:
        print(f"  lookup 실패: {e}")
        return ""


def main():
    d = json.load(open(PATH, encoding="utf-8"))

    existing_ids = {s["id"] for s in d["meta"]["sources"]}
    if NEW_SOURCE["id"] not in existing_ids:
        d["meta"]["sources"].append(NEW_SOURCE)
        print(f"소스 추가: {NEW_SOURCE['id']}")

    added = merged = skipped = already = 0
    for title, author, age, why in BOOKS:
        print(f"처리: {title} ({author})...", end=" ", flush=True)
        isbn = fetch_isbn(title, author)
        if not isbn:
            print("ISBN 없음 - 건너뜀")
            skipped += 1
            time.sleep(0.3)
            continue
        isbn = str(isbn).replace("-", "")
        if isbn in d["books"]:
            existing = d["books"][isbn]
            lists = set(existing.get("lists", []))
            changed = False
            if "textbook" not in lists:
                lists.add("textbook")
                existing["lists"] = sorted(lists)
                changed = True
            if not existing.get("why") and why:
                existing["why"] = why
                changed = True
            # 교과서 지정 학년으로 덮어씀 (유아->1학년 등)
            if existing.get("targetAge") != age:
                existing["targetAge"] = age
                changed = True
            if changed:
                print(f"병합 -> {isbn}")
                merged += 1
            else:
                print("이미 있음")
                already += 1
        else:
            d["books"][isbn] = {
                "isbn": isbn,
                "title": title,
                "author": author,
                "publisher": "",
                "lists": ["textbook"],
                "year": 2024,
                "targetAge": age,
                "genre": "그림책" if age == "초등 1학년" else "동화",
                "why": why,
            }
            print(f"신규 -> {isbn}")
            added += 1
        time.sleep(0.35)

    json.dump(d, open(PATH, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    print(f"\n완료: 신규 {added}권 / 병합 {merged}권 / 이미있음 {already}권 / 건너뜀 {skipped}권")
    print(f"총 {len(d['books'])}권 / 소스 {len(d['meta']['sources'])}개")

    from collections import Counter
    ages = Counter(b.get("targetAge", "") for b in d["books"].values())
    print("\n학년 분포:")
    for k in ["유아", "초등 1학년", "초등 저학년", "초등 고학년"]:
        print(f"  {k}: {ages.get(k, 0)}권")


if __name__ == "__main__":
    main()
